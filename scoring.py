"""
Turning two numbers into one, and one number into something a person can read.

`combine_signals` is where your false-positive decision from Milestone 1
actually gets made. Everything above it — the labels, the appeal path — is
downstream of a number this function produced.

`score_to_label` is where you stop writing for a machine and start writing for
a person. A score of 0.62 means nothing to a writer.

⚠️ Your README's **Signals and Scoring** section has to name the file and
function holding your combining rule. The grader checks your code against what
you claim, so that line should read `scoring.py::combine_signals`.
"""

import config


# The three labels, exactly as a reader sees them. Written for someone who has
# never heard the word "threshold".

LABEL_HUMAN = (
    "This looks like a person wrote it. Our checks found nothing that suggests "
    "it was generated by AI."
)

LABEL_UNSURE = (
    "We can't tell either way, so we're not making a call. Our checks gave "
    "mixed or weak results, which happens often with writing people did "
    "themselves, especially short or plainly worded pieces. This is not a "
    "finding that AI was used, and nothing happens to the piece or its writer "
    "because of it."
)

LABEL_AI = (
    "This piece shows strong signs of being generated by AI: both of our "
    "checks point that way. Automated checks can be wrong. If you wrote this "
    "yourself, you can appeal, and a person will review it."
)


def combine_signals(model_score: float, style_score: float) -> float:
    """
    Combine two 0-1 signals into one 0-1 score. Higher means more likely AI.

    The rule, in words:

      1. Take a weighted average: model signal 0.6, style signal 0.4
         (config.WEIGHT_MODEL_SIGNAL / WEIGHT_STYLE_SIGNAL).
      2. **Either signal can veto an AI verdict.** If either one leans human
         (below config.VETO_BELOW, 0.5), the combined score is capped just
         under the AI threshold. It can still be "unsure"; it can't be
         "high-confidence AI".

    Why the veto: two methods disagreeing IS uncertainty, and the expensive
    mistake is one-sided. Accusing someone needs both signals to agree. The
    veto only works in one direction, though: calling something human doesn't
    need agreement, because a missed AI piece costs the site little.
    """
    model_score = min(max(float(model_score), 0.0), 1.0)
    style_score = min(max(float(style_score), 0.0), 1.0)

    combined = (
        config.WEIGHT_MODEL_SIGNAL * model_score
        + config.WEIGHT_STYLE_SIGNAL * style_score
    ) / (config.WEIGHT_MODEL_SIGNAL + config.WEIGHT_STYLE_SIGNAL)

    if min(model_score, style_score) < config.VETO_BELOW:
        combined = min(combined, config.AI_THRESHOLD - 0.01)

    return round(min(max(combined, 0.0), 1.0), 4)


def score_to_label(score: float, word_count: int | None = None) -> tuple[str, str]:
    """
    Turn a score into (guess, label_text).

        score <  HUMAN_THRESHOLD           -> ("human",  LABEL_HUMAN)
        HUMAN_THRESHOLD <= score <= AI     -> ("unsure", LABEL_UNSURE)
        score >  AI_THRESHOLD              -> ("ai",     LABEL_AI)

    The bands are half-open on purpose, so every score from 0.0 to 1.0 lands in
    exactly one of them, with no gaps.

    Text shorter than config.MIN_WORDS_TO_JUDGE is always "unsure", whatever
    its score: neither signal has enough to go on, and a confident verdict on
    a 30-word poem would be a guess dressed up as a finding.
    """
    if word_count is not None and word_count < config.MIN_WORDS_TO_JUDGE:
        return "unsure", LABEL_UNSURE
    if score > config.AI_THRESHOLD:
        return "ai", LABEL_AI
    if score < config.HUMAN_THRESHOLD:
        return "human", LABEL_HUMAN
    return "unsure", LABEL_UNSURE


def label_ranges() -> list[tuple[str, str]]:
    """
    The score range each label covers. Your README needs these beside the
    label text — given to you so the numbers can't drift apart from config.py.
    """
    return [
        ("high-confidence human", f"0.00 – under {config.HUMAN_THRESHOLD:.2f}"),
        ("unsure", f"{config.HUMAN_THRESHOLD:.2f} – {config.AI_THRESHOLD:.2f}"),
        ("high-confidence AI", f"over {config.AI_THRESHOLD:.2f} – 1.00"),
    ]
